//! Lowers R5900 functions to Rust source that runs on `ps2-core`'s
//! recompiled-code interface (`ps2_core::rec`).
//!
//! Each guest function becomes `fn f_XXXXXXXX(c: &mut Ctx<'_>)`: a loop over
//! a `match` on the address of the block to run, so the function can start
//! at any of its blocks. Each block starts with an instruction-budget check
//! and counts its instructions in advance; every instruction then follows
//! the shared semantics, either written out (ALU, shifts, loads and stores,
//! branches, common FPU operations) or through `Ctx::exec`. The exits that
//! hand control back to the machine are described in `ps2_core::rec`.
//!
//! [`module`] generates a set of functions as one Rust module, with a
//! `BLOCKS` table of every block start; calls between functions of the same
//! module are direct, everything else goes through the table at run time.
//!
//! [`vu`] translates VU microcode overlays the same way.

mod lower;
pub mod vu;

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use ps2_analysis::{Cfg, Discovery, Function, Image};
use ps2_isa::ee::{Flow, Insn, Op};

pub use lower::lowered_inline;

/// The Rust name of the function starting at `address`.
#[must_use]
pub fn name(address: u32) -> String {
    format!("f_{address:08x}")
}

/// The blocks of a function as code generation splits them: the control-flow
/// graph's blocks, plus a block after every instruction that hands control to
/// the machine and back (system calls, `ei`, writes to COP0 Status), so the
/// machine can resume compiled code right after it.
#[must_use]
pub fn leaders(image: &Image, discovery: &Discovery, function: &Function) -> BTreeSet<u32> {
    let cfg = Cfg::build(image, function, &discovery.jump_tables);
    let mut leaders: BTreeSet<u32> = cfg.blocks.iter().map(|b| b.start).collect();
    for at in (function.start..function.end).step_by(4) {
        let insn = Insn::decode(image.word(at).unwrap_or(0));
        let resumes = matches!(insn.op().flow(), Flow::Syscall | Flow::Break | Flow::Eret)
            || matches!(insn.op(), Op::Invalid | Op::Ei)
            || (insn.op() == Op::Mtc0 && usize::from(insn.rd()) == lower::COP0_STATUS);
        if resumes && at + 4 < function.end {
            leaders.insert(at + 4);
        }
    }
    leaders
}

/// Rust source for `functions`, as one module: the functions, and
/// `BLOCKS`, every block start with the function that runs it.
#[must_use]
pub fn module(image: &Image, discovery: &Discovery, functions: &[&Function]) -> String {
    let local: BTreeMap<u32, String> = functions.iter().map(|f| (f.start, name(f.start))).collect();
    let mut out = String::new();
    let mut blocks = Vec::new();
    for function in functions {
        let leaders = leaders(image, discovery, function);
        blocks.extend(leaders.iter().map(|&at| (at, function.start)));
        lower::function(&mut out, image, function, &leaders, &local);
    }
    let mut table = String::from(
        "/// Every block start, with the function that runs it.\n\
         pub static BLOCKS: &[(u32, GuestFn)] = &[\n",
    );
    for (at, function) in blocks {
        let _ = writeln!(table, "    (0x{at:08x}, {}),", name(function));
    }
    table.push_str("];\n");
    format!(
        "// Generated by ps2-codegen: do not edit.\n\
         use ps2_core::rec::{{Ctx, Exit, GuestFn}};\n\
         #[allow(unused_imports)]\n\
         use ps2_core::float as fl;\n\n\
         {table}\n{out}"
    )
}
